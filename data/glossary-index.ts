export function getByLetter(letter: string): GlossaryEntry[] {
  const target = letter.toUpperCase();
  return GLOSSARY_INDEX.filter((e) => e.letter === target);
}

export function getAvailableLetters(): string[] {
  const letters = new Set<string>();
  for (const entry of GLOSSARY_INDEX) {
    letters.add(entry.letter);
  }
  return Array.from(letters).sort();
}
